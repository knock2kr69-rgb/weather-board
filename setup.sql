create table public.wx_tasks (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) > 0),
  region text not null check (region in ('세종', '대전', '태안', '보령')),
  kind text not null check (kind in ('야외', '고소', '실내')),
  owner text not null check (char_length(btrim(owner)) > 0),
  created_at timestamptz not null default now()
);

alter table public.wx_tasks enable row level security;

revoke all on table public.wx_tasks from anon, authenticated;
grant select, insert on table public.wx_tasks to anon;
grant usage, select on sequence public.wx_tasks_id_seq to anon;

create policy "공개 일정 조회"
on public.wx_tasks
for select
to anon
using (true);

create policy "공개 일정 추가"
on public.wx_tasks
for insert
to anon
with check (
  char_length(btrim(title)) > 0
  and region in ('세종', '대전', '태안', '보령')
  and kind in ('야외', '고소', '실내')
  and char_length(btrim(owner)) > 0
);

